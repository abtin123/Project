  /// جدا از [_localizedValues] که همراه خود اپ کامپایل می‌شود. با
  /// [registerDownloadedLanguage] پر می‌شود (هم موقع نصب دستی، هم موقع
  /// بازیابیِ بسته‌های قبلاً دانلودشده در شروع اپ).
  static final Map<String, Map<String, String>> _downloadedValues = {};

  /// یک بسته‌ی زبانِ دانلودشده را در حافظه ثبت می‌کند تا [get] بتواند از آن
  /// استفاده کند. کلیدهایی که در بسته نباشند همچنان از فارسی/انگلیسیِ
  /// درون‌اپ گرفته می‌شوند (بسته‌ی ناقص هم اپ را خراب نمی‌کند).
  static void registerDownloadedLanguage(
      String code, Map<String, String> values) {
    _downloadedValues[code] = values;
  }

  static void unregisterDownloadedLanguage(String code) {
    _downloadedValues.remove(code);
  }

  /// Loads one of the two locale JSON files bundled with the app (fa/en).
  /// All other locales are registered from downloaded ABL packs.
  static Future<bool> loadBundledLanguage(String code) async {
    if (code == 'fa' || _downloadedValues.containsKey(code)) return true;
    try {
      final raw = await rootBundle.loadString('assets/local/$code.json');
      final decoded = jsonDecode(raw);
      if (decoded is! Map) return false;
      final values = decoded
          .map((key, value) => MapEntry(key.toString(), value.toString()));
      if (values.isEmpty) return false;
      _downloadedValues.putIfAbsent(code, () => values);
      return true;
    } catch (_) {
      return false;
    }
  }

